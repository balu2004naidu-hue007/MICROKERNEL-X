#!/usr/bin/env python3
"""Validate the generated MICROKERNEL-X dashboard snapshot."""

import json
from pathlib import Path

SNAPSHOT = Path(__file__).resolve().parent.parent / "docs" / "demo-data.json"
REQUIRED_EVENTS = {
    "TASK_SCHEDULED",
    "CONTEXT_SWITCH",
    "TASK_PROGRESS",
    "TASK_FAULT",
    "RECOVERY_START",
    "RECOVERY_SUCCESS",
    "TASK_ISOLATED",
    "IPC_SEND",
    "IPC_RECEIVE",
    "MUTEX_LOCK",
    "MUTEX_WAIT",
    "MUTEX_UNLOCK",
    "PRIORITY_INHERIT",
    "PRIORITY_RESTORE",
}


def main() -> int:
    if not SNAPSHOT.is_file():
        raise SystemExit("FAIL: dashboard snapshot is missing; run make dashboard-demo")

    data = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1:
        raise SystemExit("FAIL: unsupported dashboard snapshot schema")
    if not data.get("source", "").startswith("Generated by dashboard_demo.c"):
        raise SystemExit("FAIL: snapshot source is not the C kernel dashboard demo")

    events = data.get("events")
    tasks = data.get("tasks")
    if not isinstance(events, list) or not events:
        raise SystemExit("FAIL: dashboard snapshot has no trace events")
    if not isinstance(tasks, list) or len(tasks) < 3:
        raise SystemExit("FAIL: dashboard snapshot has no task registry")

    event_types = {event.get("type") for event in events}
    missing = sorted(REQUIRED_EVENTS - event_types)
    if missing:
        raise SystemExit("FAIL: missing expected kernel events: " + ", ".join(missing))

    sequences = [event.get("sequence") for event in events]
    if sequences != list(range(1, len(events) + 1)):
        raise SystemExit("FAIL: trace event sequence is not chronological")

    states = {task.get("state") for task in tasks}
    if not {"READY", "RUNNING", "FAULTED"}.issubset(states):
        raise SystemExit("FAIL: task snapshot does not show ready, running and faulted states")

    recovery = next((task for task in tasks if task.get("name") == "RecoveryTask"), None)
    isolated = next((task for task in tasks if task.get("name") == "IsolationProbe"), None)
    if recovery is None or recovery.get("successful_recoveries") != 1:
        raise SystemExit("FAIL: verified task recovery is missing from the snapshot")
    if isolated is None or not isolated.get("isolated"):
        raise SystemExit("FAIL: bounded task isolation is missing from the snapshot")

    pool = data.get("memory_pool", {})
    if (pool.get("total_blocks") != 4 or pool.get("free_blocks") != 3 or
            pool.get("free_bitmap") != 0b1101):
        raise SystemExit("FAIL: memory-pool bitmap snapshot is inconsistent with the demo exercise")

    print(
        "PASS: dashboard snapshot schema, tasks, scheduler, mutex, IPC, "
        "watchdog, recovery, isolation and memory-pool data"
    )
    print(f"PASS: {len(tasks)} tasks and {len(events)} chronological kernel events")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
