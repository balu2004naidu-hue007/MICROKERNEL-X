#include "trace.h"

#define DEMO_POOL_BLOCK_SIZE 32U
#define DEMO_POOL_BLOCK_COUNT 4U

static void DemoTask(TaskControlBlock *task)
{
    (void)task;
}

static const char *TaskStateName(TaskState state)
{
    switch (state)
    {
        case TASK_READY:   return "READY";
        case TASK_RUNNING: return "RUNNING";
        case TASK_BLOCKED: return "BLOCKED";
        case TASK_WAITING: return "WAITING";
        case TASK_FAULTED: return "FAULTED";
        default:           return "UNKNOWN";
    }
}

static void WriteJsonString(FILE *output, const char *value)
{
    fputc('"', output);
    if (value != NULL)
    {
        for (const unsigned char *p = (const unsigned char *)value;
             *p != '\0'; ++p)
        {
            switch (*p)
            {
                case '"': fputs("\\\"", output); break;
                case '\\': fputs("\\\\", output); break;
                case '\n': fputs("\\n", output); break;
                case '\r': fputs("\\r", output); break;
                case '\t': fputs("\\t", output); break;
                default:
                    if (*p < 0x20U)
                    {
                        fprintf(output, "\\u%04x", (unsigned int)*p);
                    }
                    else
                    {
                        fputc((int)*p, output);
                    }
                    break;
            }
        }
    }
    fputc('"', output);
}

static int WriteSnapshot(
    const char *path,
    TaskControlBlock *const tasks[],
    size_t task_count,
    const TaskRegistry *registry,
    size_t pool_free_blocks,
    uint32_t pool_free_bitmap)
{
    FILE *output = fopen(path, "w");
    if (output == NULL)
    {
        perror(path);
        return -1;
    }

    TraceEvent events[TRACE_BUFFER_SIZE];
    unsigned int event_count = Kernel_Trace_Copy(events, TRACE_BUFFER_SIZE);

    unsigned int counts[TRACE_PRIORITY_RESTORE + 1] = {0U};
    for (unsigned int i = 0U; i < event_count; ++i)
    {
        if ((unsigned int)events[i].type <= (unsigned int)TRACE_PRIORITY_RESTORE)
        {
            counts[(unsigned int)events[i].type]++;
        }
    }

    fprintf(output,
        "{\n"
        "  \"schema_version\": 1,\n"
        "  \"project\": \"MICROKERNEL-X\",\n"
        "  \"profile\": \"Deterministic host demonstration\",\n"
        "  \"source\": \"Generated by dashboard_demo.c using the kernel C APIs\",\n"
        "  \"tick\": %lu,\n"
        "  \"scheduler\": {\"tasks\": %d, \"decisions\": %lu, \"context_switches\": %lu},\n"
        "  \"memory_pool\": {\"total_blocks\": %u, \"free_blocks\": %zu, \"free_bitmap\": %u},\n",
        Scheduler_GetTick(), registry->task_count,
        registry->scheduler_decisions, registry->context_switches,
        DEMO_POOL_BLOCK_COUNT, pool_free_blocks, pool_free_bitmap);

    fputs("  \"event_counts\": {", output);
    for (unsigned int type = 0U; type <= (unsigned int)TRACE_PRIORITY_RESTORE; ++type)
    {
        if (type != 0U)
        {
            fputs(",", output);
        }
        fprintf(output, "\n    ");
        WriteJsonString(output, Kernel_Trace_GetEventName((TraceEventType)type));
        fprintf(output, ": %u", counts[type]);
    }
    fputs("\n  },\n", output);

    fputs("  \"tasks\": [\n", output);
    for (size_t i = 0U; i < task_count; ++i)
    {
        const TaskControlBlock *task = tasks[i];
        fprintf(output, "    {\"id\": %d, \"name\": ", task->id);
        WriteJsonString(output, task->name);
        fputs(", \"state\": ", output);
        WriteJsonString(output, TaskStateName(task->state));
        fprintf(output,
            ", \"priority\": %d, \"base_priority\": %d, \"progress\": %lu, "
            "\"restarts\": %lu, \"successful_recoveries\": %lu, "
            "\"faults\": %lu, \"isolated\": %s, \"stack_high_water_bytes\": %zu}%s\n",
            task->priority, task->base_priority, task->progress_count,
            task->restart_count, task->successful_recoveries, task->fault_count,
            task->isolated ? "true" : "false",
            Task_GetStackHighWaterUsage(task),
            (i + 1U == task_count) ? "" : ",");
    }
    fputs("  ],\n", output);

    fputs("  \"events\": [\n", output);
    for (unsigned int i = 0U; i < event_count; ++i)
    {
        fprintf(output, "    {\"sequence\": %u, \"tick\": %lu, \"type\": ",
                i + 1U, events[i].tick);
        WriteJsonString(output, Kernel_Trace_GetEventName(events[i].type));
        fputs(", \"task\": ", output);
        WriteJsonString(output, events[i].task_name);
        fprintf(output, "}%s\n", (i + 1U == event_count) ? "" : ",");
    }
    fputs("  ]\n}\n", output);

    int write_failed = ferror(output);
    if (fclose(output) != 0)
    {
        write_failed = 1;
    }
    return write_failed ? -1 : 0;
}

int main(int argc, char **argv)
{
    const char *output_path =
        (argc > 1) ? argv[1] : "docs/demo-data.json";

    TaskControlBlock sensor_task;
    TaskControlBlock communication_task;
    TaskControlBlock worker_task;
    TaskControlBlock recovery_task;
    TaskControlBlock isolation_task;
    TaskControlBlock *tasks[] = {
        &sensor_task, &communication_task, &worker_task,
        &recovery_task, &isolation_task
    };
    TaskRegistry registry;
    KernelMutex shared_resource;

    union
    {
        max_align_t alignment;
        unsigned char bytes[DEMO_POOL_BLOCK_SIZE * DEMO_POOL_BLOCK_COUNT];
    } pool_storage;
    KernelMemoryPool pool = {0};

    Kernel_Trace_Init();
    Kernel_IPC_Init();
    Scheduler_Init(&registry);

    Task_Init(&sensor_task, 1, 4, "SensorTask", DemoTask);
    Task_Init(&communication_task, 2, 4, "CommunicationTask", DemoTask);
    Task_Init(&worker_task, 3, 2, "WorkerTask", DemoTask);
    Task_Init(&recovery_task, 4, 1, "RecoveryTask", DemoTask);
    Task_Init(&isolation_task, 5, 1, "IsolationProbe", DemoTask);

    for (size_t i = 0U; i < sizeof(tasks) / sizeof(tasks[0]); ++i)
    {
        if (Scheduler_AddTask(&registry, tasks[i]) != 0)
        {
            fputs("Dashboard demo: task registration failed.\n", stderr);
            return 1;
        }
    }

    if (Scheduler_SelectNext(&registry) != &sensor_task)
    {
        fputs("Dashboard demo: initial scheduling failed.\n", stderr);
        return 1;
    }
    Scheduler_AdvanceTick();
    Scheduler_TaskProgress(&sensor_task);

    registry.reschedule_pending = 1;
    registry.reschedule_reason = RESCHEDULE_TIMESLICE;
    if (Scheduler_SelectNext(&registry) != &communication_task)
    {
        fputs("Dashboard demo: second scheduling decision failed.\n", stderr);
        return 1;
    }
    Scheduler_AdvanceTick();
    Scheduler_TaskProgress(&communication_task);

    Kernel_Mutex_Init(&shared_resource);
    if (Kernel_Mutex_Lock(&shared_resource, &worker_task) != 0 ||
        Kernel_Mutex_Lock(&shared_resource, &sensor_task) != 1 ||
        Kernel_Mutex_Unlock(&shared_resource, &worker_task) != 0 ||
        Kernel_Mutex_ValidateState(&shared_resource) != 0)
    {
        fputs("Dashboard demo: mutex handoff scenario failed.\n", stderr);
        return 1;
    }

    communication_task.state = TASK_RUNNING;
    Kernel_IPC_RegisterReceiver(&communication_task);
    Kernel_IPC_Wait(&communication_task);
    if (communication_task.state != TASK_WAITING ||
        Kernel_IPC_Send("temperature=24.8") != 0)
    {
        fputs("Dashboard demo: IPC wake-up scenario failed.\n", stderr);
        return 1;
    }
    char message[IPC_MESSAGE_SIZE];
    if (Kernel_IPC_Receive(message, sizeof(message)) != 0 ||
        strcmp(message, "temperature=24.8") != 0)
    {
        fputs("Dashboard demo: IPC receive scenario failed.\n", stderr);
        return 1;
    }

    recovery_task.state = TASK_RUNNING;
    recovery_task.progress_enabled = 1;
    recovery_task.last_progress_tick = Scheduler_GetTick();

    isolation_task.state = TASK_RUNNING;
    isolation_task.progress_enabled = 1;
    isolation_task.last_progress_tick = Scheduler_GetTick();
    isolation_task.recovery_attempts = MAX_RECOVERY_ATTEMPTS;

    for (unsigned int i = 0U; i <= TASK_WATCHDOG_THRESHOLD; ++i)
    {
        Scheduler_AdvanceTick();
    }
    Scheduler_CheckTaskWatchdog(&registry);

    if (recovery_task.state != TASK_FAULTED ||
        isolation_task.state != TASK_FAULTED)
    {
        fputs("Dashboard demo: watchdog fault scenario failed.\n", stderr);
        return 1;
    }

    Scheduler_RecoverFaultedTask(&registry, &recovery_task);
    recovery_task.state = TASK_RUNNING;
    Scheduler_TaskProgress(&recovery_task);
    Scheduler_VerifyRecovery(&registry, &recovery_task);
    Scheduler_RecoverFaultedTask(&registry, &isolation_task);

    if (Kernel_MemoryPool_Init(&pool, pool_storage.bytes,
                               DEMO_POOL_BLOCK_SIZE,
                               DEMO_POOL_BLOCK_COUNT) != 0)
    {
        fputs("Dashboard demo: memory-pool setup failed.\n", stderr);
        return 1;
    }
    void *first_block = Kernel_MemoryPool_Alloc(&pool);
    void *second_block = Kernel_MemoryPool_Alloc(&pool);
    if (first_block == NULL || second_block == NULL ||
        Kernel_MemoryPool_Free(&pool, first_block) != 0)
    {
        fputs("Dashboard demo: memory-pool exercise failed.\n", stderr);
        return 1;
    }

    if (WriteSnapshot(output_path, tasks,
                      sizeof(tasks) / sizeof(tasks[0]),
                      &registry,
                      Kernel_MemoryPool_GetFreeCount(&pool),
                      pool.free_bitmap) != 0)
    {
        fprintf(stderr, "Dashboard demo: could not write %s.\n", output_path);
        return 1;
    }

    printf("Dashboard data generated from kernel C APIs: %s\n", output_path);
    printf("Tasks: %d | Scheduler decisions: %lu | Context switches: %lu\n",
           registry.task_count, registry.scheduler_decisions,
           registry.context_switches);
    TraceEvent retained_events[TRACE_BUFFER_SIZE];
    unsigned int retained_count =
        Kernel_Trace_Copy(retained_events, TRACE_BUFFER_SIZE);
    printf("Trace events retained: %u | Memory-pool blocks free: %zu/%u\n",
           retained_count, Kernel_MemoryPool_GetFreeCount(&pool),
           DEMO_POOL_BLOCK_COUNT);
    return 0;
}
